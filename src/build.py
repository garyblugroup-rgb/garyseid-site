import base64
t = open('template.html').read()
b64 = lambda f: 'data:image/jpeg;base64,' + base64.b64encode(open(f, 'rb').read()).decode()
h = b64('head1.jpg')
l = b64('logo_web.jpg')
g = b64('hero_web.jpg')
c = b64('closing_web.jpg')
r = b64('ranch_web.jpg')
d = b64('door_web.jpg')
st = b64('starter_web.jpg')
ce = b64('celebrate_web.jpg')
kw = 'data:image/png;base64,' + base64.b64encode(open('kw_web.png', 'rb').read()).decode()
out = t.replace('{{HEADSHOT}}', h).replace('{{LOGO}}', l).replace('{{HEROBG}}', g).replace('{{CLOSING}}', c).replace('{{RANCH}}', r).replace('{{DOOR}}', d).replace('{{STARTER}}', st).replace('{{CELEBRATE}}', ce).replace('{{KWLOGO}}', kw)
open('gary-seid-site.html', 'w').write(out)
open('preview.html', 'w').write(out)
print('ok')
